"""
Generates modules/game_autoloot/itemdata.lua: every named, pickupable item of the sibling game-server
with the *client* id the Auto Loot dialog needs (Item.create / loot matching use client ids).

The client does not load items.otb/items.xml, so item names are not available at runtime. Names live in
items.xml keyed by *server* id; items.otb maps server id -> client id (see generate_npcshopdata.py,
whose otb/xml readers are reused here).

Re-run whenever server-side items.xml or items.otb change:
    py tools/generate_autoloot_itemdata.py
"""
import importlib.util
import os
import struct
import xml.etree.ElementTree as ET

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
CLIENT_ROOT = os.path.dirname(SCRIPT_DIR)
OUTPUT_LUA = os.path.join(CLIENT_ROOT, "modules", "game_autoloot", "itemdata.lua")

OTB_FLAG_PICKUPABLE = 1 << 5
OTB_GROUP_GROUND = 1
OTB_GROUP_SPLASH = 10
OTB_GROUP_FLUID = 11

_spec = importlib.util.spec_from_file_location(
    "generate_npcshopdata", os.path.join(SCRIPT_DIR, "generate_npcshopdata.py"))
shopdata = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(shopdata)


def load_pickupable_client_ids(path):
    """Returns {server id: client id} for every pickupable, non-ground/splash/fluid item in items.otb."""
    with open(path, "rb") as f:
        data = f.read()

    root, _ = shopdata._parse_otb_node(data, 4)

    result = {}
    for node in root["children"]:
        if node["type"] in (OTB_GROUP_GROUND, OTB_GROUP_SPLASH, OTB_GROUP_FLUID):
            continue

        props = node["props"]
        flags = struct.unpack_from("<I", props, 0)[0]
        if not flags & OTB_FLAG_PICKUPABLE:
            continue

        offset = 4
        server_id = None
        client_id = None
        while offset < len(props):
            attrib = props[offset]
            datalen = struct.unpack_from("<H", props, offset + 1)[0]
            value = props[offset + 3:offset + 3 + datalen]
            if attrib == shopdata.OTB_ITEM_ATTR_SERVERID and datalen == 2:
                server_id = struct.unpack("<H", value)[0]
            elif attrib == shopdata.OTB_ITEM_ATTR_CLIENTID and datalen == 2:
                client_id = struct.unpack("<H", value)[0]
            offset += 3 + datalen

        if server_id is not None and client_id is not None:
            result[server_id] = client_id
    return result


def load_corpse_client_ids():
    """Client ids of every item the server marks with a corpseType attribute (monster corpses)."""
    all_client_ids = shopdata.load_client_ids(shopdata.ITEMS_OTB)
    corpses = set()
    for item in ET.parse(shopdata.ITEMS_XML).getroot().findall("item"):
        if not any(a.get("key") == "corpseType" for a in item.findall("attribute")):
            continue
        if item.get("id"):
            server_ids = [int(item.get("id"))]
        else:
            server_ids = range(int(item.get("fromid")), int(item.get("toid")) + 1)
        for server_id in server_ids:
            if server_id in all_client_ids:
                corpses.add(all_client_ids[server_id])
    return sorted(corpses)


def main():
    names = shopdata.load_item_names(shopdata.ITEMS_XML)
    client_ids = load_pickupable_client_ids(shopdata.ITEMS_OTB)

    entries = {}
    for server_id, client_id in client_ids.items():
        name = names.get(server_id)
        if name and client_id not in entries:
            entries[client_id] = name

    ordered = sorted(entries.items(), key=lambda e: (e[1].lower(), e[0]))

    with open(OUTPUT_LUA, "w", encoding="utf-8") as f:
        f.write("-- Generated by tools/generate_autoloot_itemdata.py -- do not edit by hand.\n")
        f.write("AutoLootItemData = {\n")
        for client_id, name in ordered:
            escaped = name.replace("\\", "\\\\").replace('"', '\\"')
            f.write('    { id = %d, name = "%s" },\n' % (client_id, escaped))
        f.write("}\n\n")

        corpses = load_corpse_client_ids()
        f.write("AutoLootCorpseIds = {\n")
        for client_id in corpses:
            f.write("    [%d] = true,\n" % client_id)
        f.write("}\n")

    print(f"Generated {OUTPUT_LUA} with {len(ordered)} items and {len(corpses)} corpse ids")


if __name__ == "__main__":
    main()
